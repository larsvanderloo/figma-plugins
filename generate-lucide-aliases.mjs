#!/usr/bin/env node
// Extracts only the alias mappings from @iconify-json/lucide into
// src/sandbox/lucide-aliases.ts (~7 KB) so the icon-swap cache matches old and
// current Lucide names; importing the full icons.json would add ~537 KB raw.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = here;
const lucidePath = resolve(repoRoot, 'node_modules/@iconify-json/lucide/icons.json');
const outPath = resolve(repoRoot, 'src/sandbox/lucide-aliases.ts');

const data = JSON.parse(readFileSync(lucidePath, 'utf8'));
const aliases = data.aliases ?? {};

const aliasToParent = {};
const parentToAliases = {};
for (const [name, info] of Object.entries(aliases)) {
  const parent = info?.parent;
  if (typeof parent !== 'string' || parent.length === 0) continue;
  aliasToParent[name] = parent;
  if (!parentToAliases[parent]) parentToAliases[parent] = [];
  parentToAliases[parent].push(name);
}

const aliasCount = Object.keys(aliasToParent).length;
const parentCount = Object.keys(parentToAliases).length;

const header = `// GENERATED by \`generate-lucide-aliases.mjs\` from \`@iconify-json/lucide/icons.json\`
// — do not edit by hand; regenerate after a Lucide version bump. Curated alias
// extract so the sandbox bundle stays small (~7 KB vs the full 537 KB icons.json).
// Counts at generation: ${aliasCount} aliases across ${parentCount} parents.
`;

const sortedAliases = Object.keys(aliasToParent).sort();
const sortedParents = Object.keys(parentToAliases).sort();

const aliasLines = sortedAliases.map((k) => `  '${k}': '${aliasToParent[k]}',`).join('\n');

const parentLines = sortedParents
  .map((p) => {
    const list = parentToAliases[p].sort();
    if (list.length === 1) return `  '${p}': ['${list[0]}'],`;
    return `  '${p}': [\n    '${list.join("',\n    '")}',\n  ],`;
  })
  .join('\n');

const out = `${header}
/** Old/alias name → current parent name. */
export const LUCIDE_ALIAS_TO_PARENT: { readonly [alias: string]: string } = {
${aliasLines}
};

/** Current parent name → all old/alias names that point to it. */
export const LUCIDE_PARENT_TO_ALIASES: { readonly [parent: string]: ReadonlyArray<string> } = {
${parentLines}
};

/**
 * Returns every name that refers to the same Lucide icon: the input
 * itself, its parent (if it's an alias), and all sibling aliases of
 * that parent. Used to register library-icon-swap cache entries under
 * every variant so a picker emitting the current name resolves even
 * when the Figma library was built with the old alias name.
 */
export function expandLucideNameVariants(name: string): string[] {
  const result = new Set<string>();
  result.add(name);

  const parent = LUCIDE_ALIAS_TO_PARENT[name];
  const canonical = parent !== undefined ? parent : name;
  result.add(canonical);

  const siblings = LUCIDE_PARENT_TO_ALIASES[canonical];
  if (siblings !== undefined) {
    for (let i = 0; i < siblings.length; i++) {
      result.add(siblings[i]);
    }
  }

  return Array.from(result);
}
`;

writeFileSync(outPath, out, 'utf8');
console.log(
  `[generate-lucide-aliases] wrote ${outPath} — ${aliasCount} aliases, ${parentCount} parents`,
);
