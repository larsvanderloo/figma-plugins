/* ---------------------------------------------------------------------------
   Body — CSS grid-template-rows collapse (zero JS measurement)

   Technique:
     - Outer div: display:grid with grid-template-rows transitioning
       between 0fr (collapsed) and 1fr (expanded).
     - overflow:hidden on outer div clips content during transition.
     - Inner div: min-height:0 allows the grid track to fully compress.

   This avoids all getBoundingClientRect() / offsetHeight reads, eliminating
   the forced-layout source of T42.21 jank from Reka's <CollapsibleContent>.

   Browser support: Chrome 117+, Firefox 109+, Safari 16.4+. All three cover
   the Figma desktop app's embedded Chromium (120+) and Figma web's
   supported browser range.
   --------------------------------------------------------------------------- */

.property-panel__body {
  display: grid;
  /* Default to open (1fr); the --closed modifier overrides to 0fr. */
  grid-template-rows: 1fr;
  overflow: hidden;
  transition: grid-template-rows 200ms ease;
}

@media (prefers-reduced-motion: reduce) {
  .property-panel__body {
    transition: none;
  }
}

.property-panel__body--open {
  grid-template-rows: 1fr;
}

.property-panel__body--closed {
  grid-template-rows: 0fr;
}

.property-panel__body-inner {
  /* min-height:0 is required — without it the grid cannot compress
     below the inner div's natural height during the 0fr phase. */
  min-height: 0;
  overflow: hidden;
}
</style>
