import { watchFile } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const rootDir = process.cwd();
const watchMode = process.argv.includes('--watch');
const packagePath = path.join(rootDir, 'package.json');
const targetPath = path.join(rootDir, 'src/ui/generated/app-version.ts');

async function readPackageVersion() {
  const pkg = JSON.parse(await readFile(packagePath, 'utf8'));
  if (typeof pkg.version !== 'string' || pkg.version.length === 0) {
    throw new Error('package.json must contain a non-empty version string');
  }
  return pkg.version;
}

async function writeAppVersion() {
  const version = await readPackageVersion();
  const contents =
    '// Generated by scripts/write-app-version.mjs. Do not edit by hand.\n' +
    `export const APP_VERSION = ${JSON.stringify(version)};\n`;

  await mkdir(path.dirname(targetPath), { recursive: true });
  await writeFile(targetPath, contents);
  console.log(`[app-version] wrote src/ui/generated/app-version.ts (${version})`);
}

await writeAppVersion();

if (watchMode) {
  let syncing = false;
  let needsSync = false;

  async function sync() {
    if (syncing) {
      needsSync = true;
      return;
    }

    syncing = true;
    try {
      await writeAppVersion();
    } catch (error) {
      console.error('[app-version] sync failed', error);
    } finally {
      syncing = false;
      if (needsSync) {
        needsSync = false;
        await sync();
      }
    }
  }

  watchFile(packagePath, { interval: 500 }, (current, previous) => {
    if (current.mtimeMs === previous.mtimeMs && current.size === previous.size) {
      return;
    }

    setTimeout(() => {
      void sync();
    }, 100);
  });

  console.log('[app-version] watching package.json');
  await new Promise(() => {});
}
