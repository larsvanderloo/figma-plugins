#!/usr/bin/env node
// The full SVG-body map ships in the iframe bundle (~537 KB raw, ~80 KB gzipped)
// so icon-pick can post the literal body to the sandbox, where
// figma.createNodeFromSvg renders it as a vector group — bypassing INSTANCE_SWAP.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const lucidePath = resolve(here, 'node_modules/@iconify-json/lucide/icons.json');
const outPath = resolve(here, 'src/ui/lucide-svgs.ts');
const namesOutPath = resolve(here, 'src/ui/lucide-icon-names.ts');

const data = JSON.parse(readFileSync(lucidePath, 'utf8'));
const icons = data.icons ?? {};
const aliases = data.aliases ?? {};
const w = data.width ?? 24;
const h = data.height ?? 24;

const bodies = {};
for (const [name, info] of Object.entries(icons)) {
  if (typeof info?.body === 'string') bodies[name] = info.body;
}
for (const [name, info] of Object.entries(aliases)) {
  const parent = info?.parent;
  if (typeof parent === 'string' && bodies[parent] !== undefined) {
    bodies[name] = bodies[parent];
  }
}

const sortedNames = Object.keys(bodies).sort();

const escape = (s) => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$/g, '\\$');

const lines = sortedNames
  .map((n) => '  ' + JSON.stringify(n) + ': `' + escape(bodies[n]) + '`,')
  .join('\n');

const out =
  '// GENERATED by `generate-lucide-svgs.mjs` from `@iconify-json/lucide/icons.json`\n' +
  '// — do not edit by hand; regenerate after a Lucide version bump.\n' +
  '// Entries: ' + sortedNames.length + ' icons (canonical + aliases).\n' +
  '\n' +
  'const W = ' + w + ';\n' +
  'const H = ' + h + ';\n' +
  '\n' +
  '/** Inner SVG body for every Lucide icon, keyed by canonical or alias name. */\n' +
  'const BODIES: { readonly [name: string]: string } = {\n' +
  lines + '\n' +
  '};\n' +
  '\n' +
  '/**\n' +
  ' * Returns a complete SVG document string for the given Lucide name, or\n' +
  ' * `null` when the name is unknown. `stroke` controls the line color; pass\n' +
  ' * a hex value like `#000000` because `figma.createNodeFromSvg` does not\n' +
  ' * resolve CSS `currentColor`.\n' +
  ' */\n' +
  'export function getLucideSvg(name: string, stroke: string = "#000000"): string | null {\n' +
  '  const body = BODIES[name];\n' +
  '  if (body === undefined) return null;\n' +
  '  const colored = body.replace(/currentColor/g, stroke);\n' +
  '  return (\n' +
  '    \'<svg xmlns="http://www.w3.org/2000/svg" width="\' + W +\n' +
  '    \'" height="\' + H +\n' +
  '    \'" viewBox="0 0 \' + W + \' \' + H +\n' +
  '    \'" fill="none" stroke="\' + stroke +\n' +
  '    \'" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\' +\n' +
  '    colored +\n' +
  '    \'</svg>\'\n' +
  '  );\n' +
  '}\n' +
  '\n' +
  '/** True if `name` is a known Lucide icon (canonical or alias). */\n' +
  'export function hasLucideIcon(name: string): boolean {\n' +
  '  return BODIES[name] !== undefined;\n' +
  '}\n';

writeFileSync(outPath, out, 'utf8');
console.log('[generate-lucide-svgs] wrote ' + outPath + ' — ' + sortedNames.length + ' icons');

const canonicalNames = Object.keys(icons).sort();
const namesOut =
  '// GENERATED by `generate-lucide-svgs.mjs` from `@iconify-json/lucide/icons.json`\n' +
  '// — do not edit by hand; regenerate after a Lucide version bump.\n' +
  '// Canonical names only (no aliases) — IconPicker renders this list.\n' +
  '\n' +
  'export const ALL_LUCIDE_ICONS: string[] = [\n' +
  canonicalNames.map((n) => "  '" + n + "',").join('\n') + '\n' +
  '];\n';

writeFileSync(namesOutPath, namesOut, 'utf8');
console.log('[generate-lucide-svgs] wrote ' + namesOutPath + ' — ' + canonicalNames.length + ' names');
